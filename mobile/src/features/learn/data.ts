export const FOR_YOU: string[] = ['titration-05', 'nausea', 'protein-plate'];

export function byId(id: string): LearnArticle | undefined { return ARTICLES.find(a => a.id === id); }
export function byCat(catId: string): LearnArticle[] { return ARTICLES.filter(a => a.cat === catId); }
export function featured(): LearnArticle | undefined { return ARTICLES.find(a => a.featured); }
export function catMeta(id: string): LearnCategory | undefined { return CATEGORIES.find(c => c.id === id); }
export function search(q: string): LearnArticle[] {
  const s = (q || '').trim().toLowerCase();
  if (!s) return [];
  return ARTICLES.filter(a =>
    a.title.toLowerCase().includes(s) ||
    a.dek.toLowerCase().includes(s) ||
    (catMeta(a.cat) !== undefined && catMeta(a.cat)!.label.toLowerCase().includes(s)));
}

export const LEARN = { CATEGORIES, ARTICLES, FOR_YOU, byId, byCat, featured, catMeta, search };
